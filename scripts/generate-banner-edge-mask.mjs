// Deterministic, offline SVG generation. No runtime animation or filters.
import {writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
const width=1600, height=160, levels=64;
const center=72, feather=80; // 50% of the existing edge strip.
const smooth=t=>t*t*(3-2*t);
// Native gradient interpolation avoids discrete alpha jumps between contours.
const stops=Array.from({length:levels},(_,i)=>{
 const t=i/(levels-1);
 return `<stop offset="${t.toFixed(6)}" stop-color="black" stop-opacity="${(1-smooth(t)).toFixed(6)}"/>`;
});
const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" preserveAspectRatio="none">
<!-- Generated by scripts/generate-banner-edge-mask.mjs. Horizontal alpha fade; no particles or animation. -->
<defs><linearGradient id="fade" gradientUnits="userSpaceOnUse" x1="0" y1="${center-feather/2}" x2="0" y2="${center+feather/2}">${stops.join('')}</linearGradient></defs>
<rect width="${width}" height="${height}" fill="url(#fade)"/>
</svg>\n`;
writeFileSync(resolve(import.meta.dirname,'../public/assets/banner-edge-mask.svg'),svg);
console.log(`Static banner mask: ${Buffer.byteLength(svg)} bytes`);